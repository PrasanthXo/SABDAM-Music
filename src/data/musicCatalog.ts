export function deduplicateTracks(tracks: Track[]): Track[] {
  const seen = new Set<string>();
  const res: Track[] = [];
  for (const t of tracks) {
    if (!t || !t.id) continue;
    const key = (t.title + ':::' + t.artist).toLowerCase().trim();
    if (!seen.has(t.id) && !seen.has(key)) {
      seen.add(t.id);
      seen.add(key);
      res.push(t);
    }
  }
  return res;
}

